export const UNITS: UnitDef[] = Object.entries(RAW).flatMap(([course, rows]) =>
  rows.map(([title, strand, prereq, summary, term], i) => ({
    id: `${course}-${i + 1}`,
    course,
    no: i + 1,
    title,
    strand,
    prereq,
    summary,
    term: term ?? (i < Math.ceil(rows.length / 2) ? 'mid' : 'final'),
  })),
);

export const UNIT_BY_ID: Record<string, UnitDef> = Object.fromEntries(UNITS.map((u) => [u.id, u]));
export const COURSE_BY_ID: Record<string, CourseDef> = Object.fromEntries(COURSES.map((c) => [c.id, c]));

export function unitsOf(courseId: string): UnitDef[] {
  return UNITS.filter((u) => u.course === courseId);
}

/** 이 단원을 선수 학습으로 삼는 단원들 (이어지는 단원) */
export function nextUnits(id: string): UnitDef[] {
  return UNITS.filter((u) => u.prereq.includes(id));
}

/** 선수 단원 전체 (깊이 depth 까지), 가까운 것부터 */
export function prereqChain(id: string, depth = 3): UnitDef[] {
  const out: UnitDef[] = [];
  const seen = new Set<string>([id]);
  let frontier = [id];
  for (let d = 0; d < depth; d++) {
    const next: string[] = [];
    for (const f of frontier) {
      for (const p of UNIT_BY_ID[f]?.prereq ?? []) {
        if (!seen.has(p)) {
          seen.add(p);
          next.push(p);
          out.push(UNIT_BY_ID[p]);
        }
      }
    }
    frontier = next;
  }
  return out;
}

export function unitLabel(u: UnitDef): string {
  return `${COURSE_BY_ID[u.course].title} ${u.no}. ${u.title}`;
}
